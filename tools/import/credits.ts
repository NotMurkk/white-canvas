// Core of `npm run credits`: assets/atlases/*.atlas.json -> assets/atlases/credits.json.
// Only packs an atlas actually uses are credited; a used pack can never be missing.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { PackManifest } from '@tdmm/map-format';

export interface CreditEntry {
  pack: string;
  name: string;
  artist: string;
  credit_line: string;
  upstream_credits: string[];
  url: string | null;
  license_spdx: string | null;
}

export interface CreditsDoc {
  generated: true;
  note: string;
  credits: CreditEntry[];
}

export interface CreditsResult {
  doc: CreditsDoc;
  errors: string[];
  warnings: string[];
  /** pack id -> atlases using it */
  usedBy: Map<string, string[]>;
  /** pack id -> manifest path (relative to root) */
  resolved: Map<string, string>;
}

const NOTE = 'Generated by tools/build-credits.ts (npm run credits) from the packs used in assets/atlases/*.atlas.json. Do not edit by hand.';

const cmp = (a: string, b: string) => {
  const x = a.toLowerCase();
  const y = b.toLowerCase();
  return x < y ? -1 : x > y ? 1 : a < b ? -1 : a > b ? 1 : 0;
};

export function buildCredits(root: string): CreditsResult {
  const errors: string[] = [];
  const warnings: string[] = [];
  const usedBy = new Map<string, string[]>();
  const resolved = new Map<string, string>();
  const atlasDir = join(root, 'assets', 'atlases');
  const atlasFiles = existsSync(atlasDir) ? readdirSync(atlasDir).filter((f) => f.endsWith('.atlas.json')).sort() : [];
  if (atlasFiles.length === 0) warnings.push('no assets/atlases/*.atlas.json found (run "npm run art:atlas" first); credits list is empty');

  for (const f of atlasFiles) {
    let doc: unknown;
    try {
      doc = JSON.parse(readFileSync(join(atlasDir, f), 'utf8'));
    } catch (e) {
      errors.push(`assets/atlases/${f}: not valid JSON (${(e as Error).message})`);
      continue;
    }
    const sources = (doc as { sources?: unknown } | null)?.sources;
    if (!Array.isArray(sources)) {
      errors.push(`assets/atlases/${f}: has no "sources" array`);
      continue;
    }
    for (const s of sources) {
      const pack = (s as { pack?: unknown } | null)?.pack;
      if (typeof pack !== 'string' || pack === '') {
        errors.push(`assets/atlases/${f}: a source entry has no "pack"`);
        continue;
      }
      const list = usedBy.get(pack) ?? [];
      if (!list.includes(f)) list.push(f);
      usedBy.set(pack, list);
    }
  }

  const credits: CreditEntry[] = [];
  for (const pack of [...usedBy.keys()].sort()) {
    const where = usedBy.get(pack)!.join(', ');
    if (!/^[a-z0-9][a-z0-9_-]*$/.test(pack)) {
      errors.push(`pack "${pack}" (used by ${where}) is not a valid pack id`);
      continue;
    }
    const candidates = [join(root, 'assets', 'packs', pack, 'pack.json'), join(root, 'assets', 'raw', pack, 'pack.json')];
    const path = candidates.find((p) => existsSync(p));
    if (!path) {
      errors.push(`pack "${pack}" is used by ${where} but has no manifest (looked for assets/packs/${pack}/pack.json and assets/raw/${pack}/pack.json)`);
      continue;
    }
    const rel = relative(root, path).replace(/\\/g, '/');
    resolved.set(pack, rel);
    let manifest: PackManifest;
    try {
      const parsed = PackManifest.safeParse(JSON.parse(readFileSync(path, 'utf8')));
      if (!parsed.success) {
        errors.push(`${rel}: does not validate (${parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('; ')})`);
        continue;
      }
      manifest = parsed.data;
    } catch (e) {
      errors.push(`${rel}: not valid JSON (${(e as Error).message})`);
      continue;
    }
    if (manifest.pack_id !== pack) errors.push(`${rel}: pack_id is "${manifest.pack_id}" but the folder is "${pack}"`);
    if (manifest.license.status === 'unknown') {
      errors.push(`pack "${pack}" (${rel}, used by ${where}) has license.status "unknown": read its terms and set "ok" or "restricted"`);
    }
    if (manifest.license.status === 'restricted') {
      warnings.push(`pack "${pack}" has license.status "restricted": make sure its terms allow this use`);
    }
    if (manifest.visibility === 'private-only' && manifest.ripped_from_official === 'full') {
      errors.push(`pack "${pack}" (${rel}, used by ${where}) is ripped from official games and private-only: ripped packs must not ship in public builds`);
    }
    if (manifest.license.credit_line === null) {
      if (manifest.source.site !== 'generated' && manifest.license.spdx !== 'CC0-1.0') {
        warnings.push(`pack "${pack}" has no credit_line; it will not appear in credits.json`);
      }
      continue;
    }
    credits.push({
      pack,
      name: manifest.name,
      artist: manifest.artist.name,
      credit_line: manifest.license.credit_line,
      upstream_credits: [...manifest.upstream_credits],
      url: manifest.source.url,
      license_spdx: manifest.license.spdx,
    });
  }
  credits.sort((a, b) => cmp(a.artist, b.artist) || cmp(a.name, b.name) || cmp(a.pack, b.pack));
  return { doc: { generated: true, note: NOTE, credits }, errors, warnings, usedBy, resolved };
}

export function serializeCredits(doc: CreditsDoc): string {
  return `${JSON.stringify(doc, null, 2)}\n`;
}

export function writeCredits(root: string, doc: CreditsDoc): string {
  const path = join(root, 'assets', 'atlases', 'credits.json');
  writeFileSync(path, serializeCredits(doc));
  return path;
}
